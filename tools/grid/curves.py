"""Hourly carbon-intensity curves per region and season for Load Shift (docs/CONCEPT.md, section 4.2).

Stylised curves: from the published trough and peak of the hour-of-day profile of 2025
(Electricity Maps, Grid in Review 2025 [S3]) the curve rises from the trough to the peak and falls back along two
half cosine waves. The result is written as integer tables (tenths of g CO₂e/kWh) into the simulation core:

    python3 tools/grid/curves.py            # writes core/src/commonMain/kotlin/de/wannerit/loadshift/core/GridCurves.kt
    python3 tools/grid/curves.py --print    # prints the tables
"""
import math
import pathlib
import sys

# (trough g/kWh, trough hour, peak g/kWh, peak hour) per region and season; Electricity Maps 2025 [S3].
# Spain publishes only the annual profile without hours: trough and peak hours are assumed (solar grid:
# lowest at 14:00, highest at 21:00).
PROFILES = {
    "norway": {
        "winter": (28.6, 15, 30.2, 2),
        "spring": (27.9, 19, 34.4, 11),
        "summer": (28.2, 22, 37.0, 11),
        "autumn": (30.4, 17, 32.9, 11),
    },
    "france": {
        "winter": (35, 2, 47, 18),
        "spring": (24, 2, 31, 18),
        "summer": (20, 2, 29, 20),
        "autumn": (23, 2, 31, 17),
    },
    "spain": {
        "year": (93.7, 14, 161.1, 21),
    },
    "greatBritain": {
        "winter": (149.1, 3, 233.8, 17),
        "spring": (123.7, 13, 222.7, 19),
        "summer": (112.9, 13, 209.6, 20),
        "autumn": (142.1, 2, 215.3, 18),
    },
    "germany": {
        "winter": (349, 11, 408, 15),
        "spring": (198, 11, 410, 2),
        "summer": (155, 11, 376, 20),
        "autumn": (257, 11, 376, 17),
    },
    "poland": {
        "winter": (684, 10, 780, 15),
        "spring": (487, 10, 745, 19),
        "summer": (456, 10, 743, 20),
        "autumn": (576, 10, 747, 16),
    },
}


def curve(low, low_hour, high, high_hour):
    """24 values at the full hours: half a cosine up from the trough to the peak, half a cosine down again."""
    rise = (high_hour - low_hour) % 24
    fall = 24 - rise
    values = []
    for h in range(24):
        since_low = (h - low_hour) % 24
        if since_low <= rise:
            t = since_low / rise
            v = low + (high - low) * (1 - math.cos(math.pi * t)) / 2
        else:
            t = (since_low - rise) / fall
            v = high - (high - low) * (1 - math.cos(math.pi * t)) / 2
        values.append(round(v * 10))
    return values


def kotlin():
    enum = {"norway": "NORWAY", "france": "FRANCE", "spain": "SPAIN", "greatBritain": "GREAT_BRITAIN",
            "germany": "GERMANY", "poland": "POLAND"}
    lines = [
        "// Generated by tools/grid/curves.py from the hour-of-day profiles of 2025 (Electricity Maps) – do not edit.",
        "",
        "package de.wannerit.loadshift.core",
        "",
        "/** Curve of a region and season; null where the source has none (then the caller falls back). */",
        "internal fun builtIn(region: GridRegion, season: Season): GridCurve? = when (region to season) {",
    ]
    for region, seasons in PROFILES.items():
        for season, profile in seasons.items():
            values = ", ".join(str(v) for v in curve(*profile))
            lines.append(f"    GridRegion.{enum[region]} to Season.{season.upper()} -> GridCurve(listOf({values}))")
    lines += ["    else -> null", "}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    if "--print" in sys.argv:
        for region, seasons in PROFILES.items():
            for season, profile in seasons.items():
                c = curve(*profile)
                print(f"{region:13} {season:7} mean {sum(c) / 240:6.1f}  " + " ".join(f"{v / 10:5.0f}" for v in c))
    else:
        root = pathlib.Path(__file__).resolve().parents[2]
        out = root / "core/src/commonMain/kotlin/de/wannerit/loadshift/core/GridCurves.kt"
        out.write_text(kotlin(), encoding="utf-8")
        print(f"written {out.relative_to(root)}")
